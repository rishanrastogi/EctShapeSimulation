"""Export simulation results for the HTML viewer.

Re-runs the synthetic pipeline for the demo shapes and writes
viewer/data.js containing, per shape:
  - ground-truth and reconstructed surface meshes (marching cubes),
  - synthetic capacitance measurements (per pair, all repeats),
  - empty-capsule baseline,
  - normalized measurements,
  - accuracy metrics.

Run:  .venv/bin/python tools/export_viewer_data.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from spacelab_ect import analysis, visualization  # noqa: E402
from spacelab_ect.calibration import Calibration  # noqa: E402
from spacelab_ect.config import DEFAULT_CONFIG  # noqa: E402
from spacelab_ect.main import demo_shapes  # noqa: E402
from spacelab_ect.mock_forward_model import MockForwardModel  # noqa: E402
from spacelab_ect.reconstruction import Reconstructor, threshold_volume  # noqa: E402


def mesh_to_dict(grid, volume) -> dict | None:
    mesh = visualization.volume_to_mesh(grid, volume)
    if mesh is None:
        return None
    tri = mesh.faces.reshape(-1, 4)[:, 1:]
    # Millimeters for comfortable Three.js scales.
    return {
        "vertices": np.round(mesh.points * 1e3, 3).ravel().tolist(),
        "faces": tri.ravel().tolist(),
    }


def main() -> None:
    config = DEFAULT_CONFIG
    model = MockForwardModel(config)
    calib = Calibration.from_model(model)
    recon = Reconstructor(model.grid, model.sensitivity.matrix)

    pairs_meta = [
        {
            "a": i,
            "b": j,
            "ringA": model.electrodes[i].ring,
            "ringB": model.electrodes[j].ring,
        }
        for i, j in model.pairs
    ]
    electrodes = [
        {
            "ring": e.ring,
            "pos": e.pos_in_ring,
            "center": np.round(e.center * 1e3, 2).tolist(),
        }
        for e in model.electrodes
    ]

    out: dict = {
        "config": {
            "radius_mm": config.capsule.radius * 1e3,
            "height_mm": config.capsule.height * 1e3,
            "nRings": config.electrodes.n_rings,
            "perRing": config.electrodes.electrodes_per_ring,
            "noise_fF": config.noise.noise_std_fF,
            "grid": [config.grid.nx, config.grid.ny, config.grid.nz],
        },
        "electrodes": electrodes,
        "pairs": pairs_meta,
        "baseline_fF": np.round(model.measure(None), 4).tolist(),
        "shapes": {},
    }

    for name, truth in demo_shapes(model).items():
        print(f"processing {name} ...")
        noisy = model.measure_with_noise(truth, n_repeats=5)
        c_avg = calib.average_repeats(noisy)
        g_norm = calib.normalize(c_avg)
        result = recon.reconstruct(g_norm)
        binary = threshold_volume(result.volume)
        report = analysis.evaluate(model.grid, truth, binary)

        out["shapes"][name] = {
            "truthMesh": mesh_to_dict(model.grid, truth),
            "reconMesh": mesh_to_dict(model.grid, binary),
            "measured_fF": np.round(c_avg, 4).tolist(),
            "repeats_fF": np.round(noisy, 4).tolist(),
            "normalized": np.round(g_norm, 5).tolist(),
            "metrics": {
                "iou": round(report.iou, 3),
                "volTrue_mL": round(report.volume_true_m3 * 1e6, 3),
                "volRecon_mL": round(report.volume_recon_m3 * 1e6, 3),
                "volErrPct": round(report.volume_error_pct, 1),
                "msd_mm": round(report.mean_surface_distance_m * 1e3, 2)
                if report.mean_surface_distance_m is not None else None,
                "hausdorff_mm": round(report.hausdorff_distance_m * 1e3, 2)
                if report.hausdorff_distance_m is not None else None,
            },
        }

    dest = ROOT / "viewer" / "data.js"
    dest.parent.mkdir(exist_ok=True)
    dest.write_text(
        "// SYNTHETIC ECT data generated by tools/export_viewer_data.py — "
        "NOT hardware measurements.\nconst ECT_DATA = "
        + json.dumps(out)
        + ";\n"
    )
    print(f"wrote {dest} ({dest.stat().st_size/1e6:.1f} MB)")


if __name__ == "__main__":
    main()
